    for part in story['parts']:
        lines.extend([f"## 第{part['id']}部　{part['title']}", ''])
        for item in part['scenes']:
            lines.extend([f"### {item['id']}　{item['title']}", '', item['narration'], ''])
            lines.extend('- '+bullet for bullet in item['bullets'])
            lines.append('')
            for formula in item['formulas']:
                lines.extend(['$$', formula, '$$', ''])
            lines.extend(['実装・保存値：'+', '.join(item.get('source_refs', [])), ''])
    (HERE/'narration.md').write_text('\n'.join(lines))
    count = sum(len(part['scenes']) for part in story['parts'])
